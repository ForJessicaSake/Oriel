export function getWork(slug: string) {
  return works.find((item) => item.slug === slug);
}

export function getExhibition(slug: string) {
  return exhibitions.find((show) => show.slug === slug);
}

export function exhibitionFor(workSlug: string) {
  return exhibitions.find((show) => show.workSlugs.includes(workSlug));
}

export function worksIn(slug: string) {
  const show = getExhibition(slug);
  if (!show) return [];
  return show.workSlugs
    .map((workSlug) => getWork(workSlug))
    .filter((item): item is Work => Boolean(item));
}
